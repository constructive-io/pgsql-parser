-- COPY direction, targets and option quoting
COPY t TO STDOUT;
COPY t FROM STDIN;
COPY (SELECT * FROM t ORDER BY a) TO STDOUT WITH DELIMITER ',';
COPY t TO STDOUT WITH (FORMAT csv, QUOTE '''', DELIMITER '|');
COPY t TO STDOUT WITH (FORMAT csv, FORCE_QUOTE (a, b), ESCAPE E'\\');
COPY t TO STDOUT WITH (FORMAT csv, FORCE_QUOTE *);
COPY t FROM STDIN WITH (FORMAT csv, FORCE_NOT_NULL (a), FORCE_NULL (b, c));
COPY t FROM STDIN WITH (FORMAT csv, FORCE_NOT_NULL *, FORCE_NULL *);
COPY t FROM STDIN WITH (FORMAT text, DELIMITER ';', NULL '\N', DEFAULT '\D', ENCODING 'sql_ascii');
COPY t FROM STDIN WITH (FORMAT binary);
COPY t FROM STDIN WITH (HEADER match);
COPY t FROM STDIN WITH (HEADER true, ON_ERROR ignore, LOG_VERBOSITY verbose);
COPY t FROM STDIN WITH (FREEZE);
COPY t FROM STDIN WITH (REJECT_LIMIT 5);
COPY t (a, b) TO 'file.csv' WITH (FORMAT csv, HEADER);
COPY t FROM PROGRAM 'gunzip < file.gz' WITH (FORMAT text);
COPY t TO PROGRAM 'gzip > file.gz';
COPY t FROM 'it''s.csv';
COPY t FROM STDIN WHERE a > 0;
COPY t FROM STDIN WITH NULL AS 'I''m null';
