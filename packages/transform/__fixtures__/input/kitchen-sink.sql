CREATE FUNCTION "my-schema".cache_users()
RETURNS void AS $$
DECLARE
  cached "my-schema".users[];
  current_user_row "my-schema".users;
BEGIN
  SELECT * INTO current_user_row FROM "my-schema".users LIMIT 1;
  cached := array_fill(current_user_row, ARRAY[1]);
END;
$$ LANGUAGE plpgsql;

