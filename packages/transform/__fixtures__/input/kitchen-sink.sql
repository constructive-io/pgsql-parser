-- =============================================================================
-- 17. CREATE FUNCTION — comprehensive PL/pgSQL function
--     This single function tests ALL PL/pgSQL-specific schema patterns:
--     - Schema-qualified function name
--     - Schema-qualified return type
--     - DECLARE with schema-qualified variable types (both schemas)
--     - SELECT FROM schema-qualified table
--     - Cross-schema references in body
-- =============================================================================
CREATE FUNCTION "my-schema".kitchen_sink_fn(
  user_id bigint
) RETURNS "my-schema".users AS $$
DECLARE
  v_user "my-schema".users;
  v_status "my-schema".user_status_type;
  v_addr "my-schema".address_type;
  v_severity "other-schema".severity_level;
  v_audit_id bigint;
BEGIN
  SELECT * INTO v_user
  FROM "my-schema".users
  WHERE id = user_id;

  v_status := v_user.status;

  INSERT INTO "other-schema".audit_log (user_id)
  VALUES (v_user.id)
  RETURNING id INTO v_audit_id;

  RETURN v_user;
END;
$$ LANGUAGE plpgsql STABLE;

-- =============================================================================
-- 17b. Second PL/pgSQL function in the same file (multi-function support)
--     - Trigger function: conditional RETURN NEW, no explicit final return
--     - Verifies each function keeps its own body and no implicit RETURN;
--       is emitted (invalid in trigger functions)
-- =============================================================================
CREATE FUNCTION "other-schema".tg_audit_users() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO "other-schema".audit_log (user_id)
    VALUES (NEW.id);
    RETURN NEW;
  END IF;
END;
$$ LANGUAGE plpgsql;

-- =============================================================================
-- 17c. Third PL/pgSQL function: cursor/exception/RAISE edge cases
--     - SCROLL cursor declaration (option must stay on the declaration)
--     - MOVE/FETCH with explicit counts and FIRST/LAST directions
--     - SQLSTATE exception condition
--     - Bare RAISE re-throw
--     - Array element assignment target
-- =============================================================================
CREATE FUNCTION "my-schema".cursor_edge_cases() RETURNS int AS $$
DECLARE
  scan_cursor SCROLL CURSOR FOR
    SELECT id FROM "my-schema".users ORDER BY id;
  ids int[] := ARRAY[0, 0, 0];
  current_id int;
BEGIN
  OPEN scan_cursor;
  MOVE FORWARD 2 FROM scan_cursor;
  FETCH PRIOR FROM scan_cursor INTO current_id;
  MOVE LAST IN scan_cursor;
  CLOSE scan_cursor;
  ids[1] := current_id;
  RETURN ids[1];
EXCEPTION
  WHEN unique_violation OR SQLSTATE '23503' THEN
    RAISE;
END;
$$ LANGUAGE plpgsql;

